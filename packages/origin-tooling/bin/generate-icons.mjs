#!/usr/bin/env node
/**
 * SVG → React TSX codegen.
 * Kaynak: src/assets/svg/*.svg
 * Çıktı:  src/components/icons/*.tsx + index.ts
 */
import { transform } from "@svgr/core";
import jsxPlugin from "@svgr/plugin-jsx";
import svgoPlugin from "@svgr/plugin-svgo";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { basename, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { format, resolveConfig } from "prettier";

const ROOT = resolve(process.env.ORIGIN_APP_ROOT ?? process.cwd());
const SVG_DIR = join(ROOT, "src/assets/svg");
const OUT_DIR = join(ROOT, "src/components/icons");
const BANNER = "// Generated by npm run icons — do not edit.\n";

function toPascalCase(kebab) {
  return kebab
    .split("-")
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

function svgStem(filename) {
  return basename(filename, ".svg");
}

async function listSvgFiles() {
  let entries;
  try {
    entries = await readdir(SVG_DIR);
  } catch (err) {
    if (err && typeof err === "object" && "code" in err && err.code === "ENOENT") {
      return [];
    }
    throw err;
  }
  return entries.filter((name) => name.endsWith(".svg")).sort();
}

async function removeStaleOutputs(svgFiles) {
  const expected = new Set(svgFiles.map((name) => `${svgStem(name)}.tsx`));
  let outputs;
  try {
    outputs = await readdir(OUT_DIR);
  } catch (err) {
    if (err && typeof err === "object" && "code" in err && err.code === "ENOENT") {
      return;
    }
    throw err;
  }

  await Promise.all(
    outputs
      .filter((name) => name.endsWith(".tsx") && !expected.has(name))
      .map((name) => rm(join(OUT_DIR, name))),
  );
}

/**
 * SVGR's transform, called directly rather than through @svgr/cli.
 *
 * The CLI's job is walking directories and naming outputs, and this file
 * already does both — all that was left was the transform. Shelling out to it
 * also meant every generated app had to carry @svgr/cli as a devDependency,
 * and with it a deprecated glob/inflight chain that nothing here ever ran.
 */
async function runSvgr(svgFiles) {
  await mkdir(OUT_DIR, { recursive: true });
  if (svgFiles.length === 0) {
    await writeGeneratedFile(
      join(OUT_DIR, "index.ts"),
      `${BANNER}// No SVG sources in src/assets/svg\n`,
    );
    return;
  }

  const config = await readSvgrConfig();
  for (const name of svgFiles) {
    const stem = svgStem(name);
    const code = await transform(
      await readFile(join(SVG_DIR, name), "utf8"),
      // svgo runs first so the JSX is built from the optimised tree.
      { ...config, plugins: [svgoPlugin, jsxPlugin] },
      // SVGR's own naming: the prefix keeps the generated output identical to
      // what @svgr/cli produced, so upgrading does not rewrite every icon.
      { componentName: `Svg${toPascalCase(stem)}`, filePath: join(SVG_DIR, name) },
    );
    await writeGeneratedFile(join(OUT_DIR, `${stem}.tsx`), `${BANNER}${code}`);
  }
}

/** The app owns how its icons are generated; without a config SVGR's defaults apply. */
async function readSvgrConfig() {
  const configPath = join(ROOT, ".svgrrc.cjs");
  try {
    const module = await import(pathToFileURL(configPath).href);
    return module.default ?? {};
  } catch (err) {
    if (
      err &&
      typeof err === "object" &&
      "code" in err &&
      (err.code === "ERR_MODULE_NOT_FOUND" || err.code === "ENOENT")
    ) {
      return {};
    }
    throw err;
  }
}

/**
 * The order `simple-import-sort` wants, so the generator and the linter agree.
 *
 * They did not. The barrel came out in filename order — plain `Array.sort`,
 * which is code-unit order and puts every capitalised name before every
 * lowercase one. `simple-import-sort/exports` compares module sources with a
 * base-sensitivity collator, where `./brand-mark` comes before
 * `./ComprehensiveCarInsurance`. So `pnpm build` regenerated a file `pnpm lint`
 * rejected, `pnpm lint:fix` produced one the next build overwrote, and which of
 * the two an app's CI saw depended on the order its steps happened to run in.
 */
const SOURCE_ORDER = new Intl.Collator("en", { sensitivity: "base", numeric: true });

function compareSources(left, right) {
  return SOURCE_ORDER.compare(left, right) || (left < right ? -1 : left > right ? 1 : 0);
}

async function writeBarrel(svgFiles) {
  const lines = svgFiles
    .map((name) => svgStem(name))
    .sort(compareSources)
    .map((stem) => `export { default as ${toPascalCase(stem)} } from "./${stem}";`);

  const content =
    lines.length > 0
      ? `${BANNER}${lines.join("\n")}\n`
      : `${BANNER}// No SVG sources in src/assets/svg\n`;

  await writeGeneratedFile(join(OUT_DIR, "index.ts"), content);
}

async function writeGeneratedFile(path, source) {
  const prettierConfig = (await resolveConfig(path)) ?? {};
  const content = await format(source, { ...prettierConfig, filepath: path });
  try {
    if ((await readFile(path, "utf8")) === content) return;
  } catch (error) {
    if (!error || typeof error !== "object" || !("code" in error) || error.code !== "ENOENT") {
      throw error;
    }
  }
  await writeFile(path, content);
}

async function main() {
  const svgFiles = await listSvgFiles();
  await removeStaleOutputs(svgFiles);
  await runSvgr(svgFiles);
  await writeBarrel(svgFiles);

  const count = svgFiles.length;
  console.log(`[icons] ${count} SVG → ${count} TSX (${OUT_DIR})`);
}

main().catch((err) => {
  console.error("[icons] failed:", err);
  process.exit(1);
});
